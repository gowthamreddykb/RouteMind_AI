"""project_audit.py - Phase 1: automated audit of the existing ML project (writes reports/ml_project_audit_report.*)."""
import ast, glob, importlib, os, re, sys
import pandas as pd
sys.path.insert(0, os.path.dirname(__file__))
from load_data import ROOT, REPORTS

def audit():
    rows, funcs, text = [], {}, {}
    for f in sorted(glob.glob(os.path.join(ROOT, "src", "*.py"))):
        src = open(f).read(); text[f] = src
        tree = ast.parse(src)
        funcs[f] = [n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))]
    all_src = "\n".join(text.values()) + "\n".join(open(f).read() for f in glob.glob(os.path.join(ROOT, "tests", "*.py")))
    for f, names in funcs.items():
        base = os.path.basename(f)
        unused = [n for n in names if not n.startswith("_") and len(re.findall(r"\b%s\b" % re.escape(n), all_src)) <= 1 and n != "main"]
        hard = re.findall(r"[\"'](?:[A-Za-z]:\\\\|/home/|/mnt/)[^\"']*[\"']", text[f])
        doc = ast.get_docstring(ast.parse(text[f])) or "(no module docstring)"
        rows.append({"file": f"src/{base}", "current_functionality": doc.splitlines()[0][:110], "functions": len(names),
                     "unused_functions": ", ".join(unused) or "-", "hardcoded_absolute_paths": ", ".join(hard) or "none",
                     "verification": "imports OK" if _imports(base) else "IMPORT FAILED"})
    return pd.DataFrame(rows)

def _imports(base):
    try:
        importlib.import_module(base[:-3]); return True
    except Exception:
        return False

STAGES = [  # (stage, module/function that implements it, check)
 ("1 Data loading", "load_data.load_dataset"), ("2 Data validation", "data_analysis.inspect"),
 ("3 Data cleaning", "data_cleaning.clean_data"), ("4 Target validation", "data_cleaning.clean_data (0/1 + per-order consistency only; NO outcome-category/eligibility logic)"),
 ("5 Leakage detection", "feature_audit.assert_no_prohibited"), ("6 Feature selection", "feature_audit.build_audits"),
 ("7 Feature engineering", "feature_engineering.engineer_order_features (calendar + order features; NO historical-rate features)"),
 ("8 Splitting", "data_splitting.group_chronological_split (single split; NO multi-period backtests)"),
 ("9 Preprocessing", "data_preprocessing.build_preprocessor"), ("10 Model training", "model_training.train_logistic / fit_xgb"),
 ("11 Hyper-parameter tuning", "hyperparameter_tuning.random_search (validation only; NO time-aware CV, NO imbalance experiment)"),
 ("12 Model comparison", "main.compare_and_select"), ("13 Threshold optimisation", "model_evaluation.select_threshold (single cost assumption; no 0.20-0.60 grid report)"),
 ("14 Calibration", "model_calibration.choose_calibration"), ("15 Evaluation", "model_evaluation.* (subgroups by mode/segment/market/quarter only; no unseen-product/category, region, FN/FP reports)"),
 ("16 Explainability", "shap_explainability.explain_rows"), ("17 Serialisation", "model_saving.save_stage_model (versioned; NO registry/approval/rollback)"),
 ("18 Model loading", "prediction.load_model (cached; no registry awareness)"), ("19 Prediction", "prediction.predict_at_order_creation (no controlled-error wrapper, no failure logging)"),
 ("20 Reporting", "main.write_summaries"),
]
GAPS = ["Target eligibility: cancelled/fraud rows (4.3%) are trained & scored as 'not late'",
        "No prediction history / outcome feedback / drift monitoring", "No champion-challenger, approval status, rollback",
        "No latency / throughput / memory benchmark", "No time-based backtests", "No false-negative / false-positive reports",
        "No unseen product/category analysis"]

def main():
    a = audit(); a.to_csv(f"{REPORTS}/ml_project_audit_files.csv", index=False)
    s = pd.DataFrame(STAGES, columns=["workflow_stage", "implementation / gap"])
    s["status"] = ["COMPLETE"] * len(s)
    for i, (st, impl) in enumerate(STAGES):
        if "NO " in impl or "no " in impl: s.loc[i, "status"] = "PARTIAL - improvement required"
    s.to_csv(f"{REPORTS}/ml_project_audit_workflow.csv", index=False)
    req = open(os.path.join(ROOT, "requirements.txt")).read().split()
    with open(f"{REPORTS}/ml_project_audit_report.txt", "w") as f:
        f.write("EXISTING ML PROJECT AUDIT (generated by src/project_audit.py)\n" + "=" * 70 + "\n\nFILES\n" + a.to_string(index=False))
        f.write("\n\nWORKFLOW STAGES\n" + s.to_string(index=False))
        f.write("\n\nIDENTIFIED GAPS\n" + "\n".join(" - " + g for g in GAPS))
        f.write(f"\n\nrequirements.txt pinned: {all('==' in r for r in req)} ({len(req)} entries)\n")
    print(a[["file", "unused_functions", "hardcoded_absolute_paths", "verification"]].to_string(index=False)); print(s.to_string(index=False))

if __name__ == "__main__":
    main()
